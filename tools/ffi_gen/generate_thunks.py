#!/usr/bin/env python3
"""Generate wire layout contracts, SoftMMU codecs, and JNI slot thunks."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BANNER = "// Generated by tools/ffi_gen/generate_thunks.py. Do not edit."
SCALARS = {
    "i8": ("int8_t", 1, "SIGNED"),
    "u8": ("uint8_t", 1, "UNSIGNED"),
    "i16": ("int16_t", 2, "SIGNED"),
    "u16": ("uint16_t", 2, "UNSIGNED"),
    "i32": ("int32_t", 4, "SIGNED"),
    "u32": ("uint32_t", 4, "UNSIGNED"),
    "i64": ("int64_t", 8, "SIGNED"),
    "u64": ("uint64_t", 8, "UNSIGNED"),
    "f32": ("float", 4, "FLOAT"),
    "f64": ("double", 8, "DOUBLE"),
    "ptr32": ("uint32_t", 4, "POINTER"),
    "ptr64": ("uint64_t", 8, "POINTER"),
    "bytes4": ("uint8_t", 4, None),
}
PROFILES = ("aarch64", "armv7", "wasm32", "x86_64")


def field_size(records, field_type):
    if field_type in SCALARS:
        return SCALARS[field_type][1]
    return records[field_type]["size"]


def validate(schema):
    if schema["version"] != 1:
        raise ValueError("unsupported schema version")
    declared = {}
    for name, record in schema["records"].items():
        size, align = record["size"], record["align"]
        if align not in (1, 2, 4, 8) or size <= 0 or size % align:
            raise ValueError(f"invalid size or alignment for {name}")
        if not record["oracle"] or set(record["oracle"]) - set(PROFILES):
            raise ValueError(f"invalid oracle profile for {name}")
        fields = set()
        end = 0
        for field in record["fields"]:
            offset = field["offset"]
            width = field_size(declared, field["type"])
            if record.get("kind") == "union":
                if offset != 0:
                    raise ValueError(f"invalid union offset for {name}.{field['name']}")
            elif offset < end:
                raise ValueError(f"overlapping fields in {name}")
            end = offset + width
            if end > size or field["name"] in fields:
                raise ValueError(f"invalid field {name}.{field['name']}")
            fields.add(field["name"])
        if not fields:
            raise ValueError(f"empty record {name}")
        declared[name] = record
    jni = schema["jni"]
    names = jni["reserved"] + jni["functions"]
    if len(jni["reserved"]) != 4 or len(names) != 233 or len(set(names)) != len(names):
        raise ValueError("expected JNI slots 0 through 232 with four reserved entries")
    if set(jni["marshallers"]) - set(jni["functions"]):
        raise ValueError("marshaller names must be callable JNI slots")


def layout_header(records, jni):
    lines = [
        BANNER, "#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "",
        "#ifdef __cplusplus",
        "namespace wa::ffi {",
        "#define WA_FFI_ASSERT static_assert",
        "#define WA_FFI_ALIGNAS alignas",
        "#define WA_FFI_ALIGNOF alignof",
        "#else",
        "#define WA_FFI_ASSERT _Static_assert",
        "#define WA_FFI_ALIGNAS _Alignas",
        "#define WA_FFI_ALIGNOF _Alignof",
        "#endif", "",
        "// These declarations describe the ABI. The codecs transfer bytes through the SoftMMU.",
    ]
    for name, record in records.items():
        kind = record.get("kind", "struct")
        packed = record.get("packed", False)
        size, align = record["size"], record["align"]
        if packed:
            lines.append("#pragma pack(push, 1)")
        lines.append(f"typedef {kind} {name} {{")
        gaps = []
        end = 0
        for index, field in enumerate(record["fields"]):
            field_type = field["type"]
            member = field["name"]
            offset = field["offset"]
            if kind == "struct" and offset > end:
                gaps.append((end, offset - end))
                lines.append(f"    uint8_t padding_{end}[{offset - end}];")
            alignment = f"WA_FFI_ALIGNAS({align}) " if index == 0 and not packed else ""
            c_type = SCALARS[field_type][0] if field_type in SCALARS else field_type
            suffix = "[4]" if field_type == "bytes4" else ""
            lines.append(f"    {alignment}{c_type} {member}{suffix};")
            end = offset + field_size(records, field_type)
        if kind == "struct" and size > end:
            gaps.append((end, size - end))
            lines.append(f"    uint8_t padding_{end}[{size - end}];")
        lines.append(f"}} {name};")
        if packed:
            lines.append("#pragma pack(pop)")
        lines.extend([
            f'WA_FFI_ASSERT(sizeof({name}) == {size}, "{name} size");',
            f'WA_FFI_ASSERT(WA_FFI_ALIGNOF({name}) == {align}, "{name} alignment");',
        ])
        for field in record["fields"]:
            member, offset = field["name"], field["offset"]
            lines.append(f'WA_FFI_ASSERT(offsetof({name}, {member}) == {offset}, "{name}.{member}");')
        for offset, width in gaps:
            member = f"padding_{offset}"
            lines.extend([
                f'WA_FFI_ASSERT(offsetof({name}, {member}) == {offset}, "{name}.{member}");',
                f'WA_FFI_ASSERT(sizeof((({name}*)0)->{member}) == {width}, "{name}.{member} width");',
            ])
        lines.append("")

    slots = jni["reserved"] + jni["functions"]
    lines.extend([
        "#undef WA_FFI_ASSERT", "#undef WA_FFI_ALIGNAS", "#undef WA_FFI_ALIGNOF", "",
        "#ifdef __cplusplus", "} // namespace wa::ffi", "#endif", "",
        f"#define WA_FFI_JNI_FIRST_FUNCTION_SLOT {len(jni['reserved'])}",
        f"#define WA_FFI_JNI_TABLE_ENTRIES {len(slots)}",
        "#define WA_FFI_JNI_SLOTS(X) \\",
    ])
    lines.extend(f"    X({index}, {name})" + (" \\" if index + 1 < len(slots) else "")
                 for index, name in enumerate(slots))
    return lines


def oracle_assertions(records):
    lines = [BANNER, ""]
    for profile in PROFILES:
        lines.append(f"#if defined(WA_FFI_ORACLE_{profile.upper()})")
        for name, record in records.items():
            if profile not in record["oracle"]:
                continue
            c_type = record["c_type"]
            is_struct = record.get("kind") != "union"
            lines.append(f"WA_CHECK_LAYOUT({name}, {c_type});")
            previous = None
            end = 0
            for field in record["fields"]:
                member = field["name"]
                if record.get("scalar_oracle"):
                    lines.append(f"WA_CHECK_ENV({name}, {member}, {c_type});")
                    continue
                actual = field.get("member", member)
                offset = field["offset"]
                if previous and is_struct and offset > end:
                    lines.append(f"WA_CHECK_GAP({name}, padding_{end}, {c_type}, {previous}, {actual});")
                lines.append(f"WA_CHECK_MEMBER({name}, {member}, {c_type}, {actual});")
                if field["type"] in SCALARS:
                    check = SCALARS[field["type"]][2]
                    if check:
                        lines.append(f"WA_CHECK_{check}({c_type}, {actual});")
                previous = actual
                end = offset + field_size(records, field["type"])
            if previous and is_struct and record["size"] > end:
                lines.append(f"WA_CHECK_TAIL({name}, padding_{end}, {c_type}, {previous});")
        lines.extend(["#endif", ""])
    return lines


def emit_codec(lines, record_name, record, records):
    codec = record["codec"]
    fields = [field for field in record["fields"] if not field.get("reserved")]
    for field in fields:
        if "host_alias" in field:
            member, alias = field["name"], field["host_alias"]
            lines.extend([
                f"template <class Host> constexpr decltype(auto) host_{member}(Host& value) {{",
                f"    if constexpr (requires {{ value.{member}; }})",
                f"        return (value.{member});",
                "    else",
                f"        return (value.{alias});",
                "}", "",
            ])

    def location(field, obj):
        member = field["name"]
        field_type = field["type"]
        target = f"{obj}.{member}"
        if "host_alias" in field:
            target = f"host_{member}({obj})"
        if "union_member" in field:
            target += "." + field["union_member"]
            field_type = next(f["type"] for f in records[field_type]["fields"]
                              if f["name"] == field["union_member"])
        wire = f"bytes + offsetof({record_name}, {member})"
        return wire, target, field_type

    lines.extend([
        f"template <class Host> bool decode_{codec}(const uint8_t* bytes, Host& out) {{",
    ])
    for field in fields:
        wire, target, field_type = location(field, "out")
        if field_type in SCALARS:
            member = field["name"]
            c_type = SCALARS[field_type][0]
            lines.extend([
                f"    const auto {member} = load_le<{c_type}>({wire});",
                f"    if (!std::in_range<decltype({target})>({member}))",
                "        return false;",
                f"    {target} = static_cast<decltype({target})>({member});",
            ])
        else:
            nested = records[field_type]["codec"]
            lines.extend([f"    if (!decode_{nested}({wire}, {target}))", "        return false;"])
    lines.extend(["    return true;", "}", "",
                  f"template <class Host> bool encode_{codec}(uint8_t* bytes, const Host& in) {{"])
    for field in fields:
        wire, target, field_type = location(field, "in")
        if field_type in SCALARS:
            c_type = SCALARS[field_type][0]
            lines.extend([f"    if (!encode_integer<{c_type}>({wire}, {target}))",
                          "        return false;"])
        else:
            nested = records[field_type]["codec"]
            lines.extend([f"    if (!encode_{nested}({wire}, {target}))", "        return false;"])
    lines.extend(["    return true;", "}", ""])


def emit_jvalue(lines, record):
    lines.extend([
        "// A jvalue has no tag. Select the accessor using the JNI method signature.",
        "class JValue {", "public:",
        "    static constexpr JValue from_bits(uint64_t bits) {",
        "        JValue value;",
        "        value.bits_ = bits;",
        "        return value;",
        "    }",
        "    constexpr uint64_t bits() const { return bits_; }", "",
    ])
    for field in record["fields"]:
        member = field["name"]
        c_type = SCALARS[field["type"]][0]
        lines.extend([
            f"    constexpr {c_type} get_{member}() const {{",
            f"        return std::bit_cast<{c_type}>(static_cast<detail::WireBitsT<{c_type}>>(bits_));",
            "    }",
            f"    constexpr void set_{member}({c_type} value) {{",
            f"        bits_ = std::bit_cast<detail::WireBitsT<{c_type}>>(value);",
            "    }", "",
        ])
    lines.extend([
        "    template <class UInt> [[nodiscard]] constexpr int32_t get_l_as(UInt& out) const {",
        "        return narrow_guest_address(get_l(), out);",
        "    }", "",
        "private:",
        "    uint64_t bits_ = 0;",
        "};",
        "static_assert(sizeof(JValue) == sizeof(Aarch64JValue));", "",
    ])


def emit_record_api(lines, name, codec, array):
    lines.extend([
        "template <class Host>",
        f"[[nodiscard]] int32_t read_{codec}(wa_softmmu_t* mmu, uint64_t address, Host& out) {{",
        f"    return detail::read_record<sizeof({name})>(",
        f"        mmu, address, out, detail::decode_{codec}<Host>);",
        "}", "",
        "template <class Host>",
        f"[[nodiscard]] int32_t write_{codec}(wa_softmmu_t* mmu, uint64_t address, const Host& in) {{",
        f"    return detail::write_record<sizeof({name})>(",
        f"        mmu, address, in, detail::encode_{codec}<Host>);",
        "}", "",
    ])
    if array:
        lines.extend([
            "template <class Host, size_t Extent>",
            f"[[nodiscard]] int32_t read_{codec}s(wa_softmmu_t* mmu, uint64_t address,",
            "                                     std::span<Host, Extent> out) {",
            f"    return detail::read_array<sizeof({name})>(",
            f"        mmu, address, std::span<Host>(out), detail::decode_{codec}<Host>);",
            "}", "",
            "template <class Host, size_t Extent>",
            f"[[nodiscard]] int32_t write_{codec}s(wa_softmmu_t* mmu, uint64_t address,",
            "                                      std::span<Host, Extent> in) {",
            "    using Value = std::remove_const_t<Host>;",
            f"    return detail::write_array<sizeof({name})>(",
            f"        mmu, address, std::span<const Value>(in), detail::encode_{codec}<Value>);",
            "}", "",
        ])


def marshall_header(records):
    lines = [
        BANNER, "#pragma once", "", '#include "abi_layouts.h"',
        '#include "../marshall_support.h"', "", "namespace wa::ffi {", "",
    ]
    emit_jvalue(lines, records["Aarch64JValue"])
    lines.extend(["namespace detail {", ""])
    for name, record in records.items():
        if record.get("codec") and record.get("kind") != "union":
            emit_codec(lines, name, record, records)

    lines.extend([
        "inline bool decode_jvalue(const uint8_t* bytes, JValue& out) {",
        "    out = JValue::from_bits(load_le<uint64_t>(bytes));",
        "    return true;",
        "}", "",
        "inline bool encode_jvalue(uint8_t* bytes, const JValue& in) {",
        "    store_le(bytes, in.bits());",
        "    return true;",
        "}", "",
        "} // namespace detail", "",
    ])
    for name, record in records.items():
        if not record.get("codec"):
            continue
        if record["codec"] != "jvalue":
            emit_record_api(lines, name, record["codec"], record.get("array", False))
    lines.extend([
        "[[nodiscard]] inline int32_t read_jvalue(wa_softmmu_t* mmu, uint64_t address, JValue& out) {",
        "    return detail::read_record<sizeof(Aarch64JValue)>(mmu, address, out,",
        "                                                    detail::decode_jvalue);",
        "}", "",
        "[[nodiscard]] inline int32_t write_jvalue(wa_softmmu_t* mmu, uint64_t address,",
        "                                          const JValue& in) {",
        "    return detail::write_record<sizeof(Aarch64JValue)>(mmu, address, in,",
        "                                                     detail::encode_jvalue);",
        "}", "",
        "[[nodiscard]] inline int32_t read_jvalues(wa_softmmu_t* mmu, uint64_t address,",
        "                                          std::span<JValue> out) {",
        "    return detail::read_array<sizeof(Aarch64JValue)>(mmu, address, out, detail::decode_jvalue);",
        "}", "",
        "[[nodiscard]] inline int32_t write_jvalues(wa_softmmu_t* mmu, uint64_t address,",
        "                                           std::span<const JValue> in) {",
        "    return detail::write_array<sizeof(Aarch64JValue)>(mmu, address, in, detail::encode_jvalue);",
        "}", "",
        "} // namespace wa::ffi",
    ])
    return lines


def jni_header(jni):
    lines = [
        BANNER, "#pragma once", "", '#include "../jni_dispatch_support.h"', "",
        "namespace wa::ffi {", "",
        "enum class JniSlot : uint16_t {",
        "#define WA_FFI_DECLARE_JNI_SLOT(index, name) name = index,",
        "    WA_FFI_JNI_SLOTS(WA_FFI_DECLARE_JNI_SLOT)",
        "#undef WA_FFI_DECLARE_JNI_SLOT",
        "};", "",
        "[[nodiscard]] inline int32_t dispatch_jni(JniSlot slot, wa_host_call_ctx_t& context,",
        "                                          const JniCallbacks& callbacks) {",
        "    const auto index = static_cast<size_t>(slot);",
        "    if (index < kJniFirstFunctionSlot || index >= kJniTableEntries ||",
        "        context.arch != WA_ARCH_ARM64 || !context.mmu)",
        "        return WA_ERR_INVALID;",
        "    if (!context.args[0])",
        "        return WA_ERR_FAULT;",
        "",
        "    try {",
        "        switch (slot) {",
    ]
    for name, helper in jni["marshallers"].items():
        lines.extend([f"        case JniSlot::{name}:",
                      f"            return detail::dispatch_{helper}(context, callbacks);"])
    lines.extend([
        "        default:",
        "            return callbacks.raw ? callbacks.raw(callbacks.user, slot, context) : WA_ERR_NOSYS;",
        "        }",
        "    } catch (const std::bad_alloc&) {",
        "        return WA_ERR_NOMEM;",
        "    } catch (const std::length_error&) {",
        "        return WA_ERR_OVERFLOW;",
        "    } catch (...) {",
        "        return WA_ERR_INTERNAL;",
        "    }",
        "}", "",
        "namespace detail {", "",
        "template <JniSlot Slot> int32_t jni_host_call(wa_host_call_ctx_t* context, void* user) {",
        "    if (!context || !user)",
        "        return WA_ERR_INVALID;",
        "    return dispatch_jni(Slot, *context, *static_cast<const JniCallbacks*>(user));",
        "}", "",
        "} // namespace detail", "",
        "struct JniSlotInfo {",
        "    JniSlot slot;",
        "    const char* name;",
        "    wa_host_symbol_fn host_call;",
        "};", "",
        "inline constexpr std::array<JniSlotInfo, kJniTableEntries> kJniDispatchTable{{",
        "#define WA_FFI_JNI_SLOT_INFO(index, name)                                               \\",
        "    {JniSlot::name, #name, index < kJniFirstFunctionSlot                                 \\",
        "                             ? nullptr : &detail::jni_host_call<JniSlot::name>},",
        "    WA_FFI_JNI_SLOTS(WA_FFI_JNI_SLOT_INFO)",
        "#undef WA_FFI_JNI_SLOT_INFO",
        "}};", "",
        "} // namespace wa::ffi",
    ])
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check committed output without writing")
    args = parser.parse_args()
    try:
        schema = json.loads((ROOT / "abi_schema.json").read_text(encoding="utf-8"))
        validate(schema)
        records, jni = schema["records"], schema["jni"]
        outputs = {
            "abi_layouts.h": layout_header(records, jni),
            "abi_layout_oracle.inc": oracle_assertions(records),
            "lp64_ilp32_marshall.h": marshall_header(records),
            "jni_vtable_thunks.h": jni_header(jni),
        }
        stale = []
        for name, lines in outputs.items():
            generated = ROOT / "generated" / name
            content = ("\n".join(lines).rstrip() + "\n").encode("utf-8")
            if generated.is_file() and generated.read_bytes() == content:
                continue
            if args.check:
                stale.append(name)
            else:
                generated.parent.mkdir(exist_ok=True)
                generated.write_bytes(content)
        if stale:
            print("Stale or missing generated files: " + ", ".join(stale), file=sys.stderr)
            print("Run python3 tools/ffi_gen/generate_thunks.py to regenerate.", file=sys.stderr)
            return 1
    except (KeyError, ValueError, OSError) as error:
        print(f"FFI generation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
